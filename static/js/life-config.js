/**
 * life-config.js —— 首页生命游戏背景配置文件
 *
 * 您可以在此处直接配置生命游戏背景的各项运行参数：
 * 1. stepMs        : 生命游戏演化速度（每代间隔毫秒数）
 * 2. cellColor     : 方块（活细胞）颜色
 * 3. bgColor       : 背景底色
 * 4. cellSize      : 方块像素大小（0 表示自适应分辨率）
 * 5. initMode      : 初始化模式选择（'preset' 预设图案播撒 vs 'random' 完全随机位置初始化）
 * 6. randomDensity : 完全随机模式下的活细胞方块初始密度
 * 7. autoReplenish : 是否自动刷新增添新方块（默认 false，仅在页面刷新时初始化）
 * 8. maxAge        : 防结壳/老化代数（0 表示纯正标准康威生命游戏，静止方块不强制消亡）
 * 9. avoidHeader   : 是否在顶部导航栏区域避让方块
 */
(function (global) {
  'use strict';

  global.LIFE_CONFIG = {
    // -------------------------------------------------------------------------
    // 1. 进行速度设置
    // -------------------------------------------------------------------------
    /**
     * 每代演化间隔时间（毫秒）。
     * 数值越小演化速度越快，数值越大演化速度越慢。
     * 常用推荐值：
     *   30  : 极速演化（约 33 代/秒）
     *   60  : 较快流畅（约 16 代/秒，默认）
     *   100 : 适中悠闲（约 10 代/秒）
     *   200 : 慢速观察（约 5 代/秒）
     */
    stepMs: 91,

    // -------------------------------------------------------------------------
    // 2. 方块颜色与背景设置
    // -------------------------------------------------------------------------
    /**
     * 方块（活细胞）颜色。
     * 支持各种标准十六进制颜色代码，例如：
     *   '#e9eddf' : 原版浅灰米白（淡雅底纹，推荐）
     *   '#2b2b2b' : 经典深黑像素
     *   '#4a90e2' : 科技蓝
     *   '#7cb342' : 自然绿
     *   '#e76f51' : 暖橙色
     */
    cellColor: '#e9eddf',

    /**
     * 画布背景底色（默认为纯白 '#ffffff'）。
     */
    bgColor: '#ffffff',

    /**
     * 每个方块像素的大小（单位：px）。
     * 设为 0 时：系统将根据屏幕分辨率自动计算最佳尺寸
     * （桌面 1080P 约 6px，4K 约 12px，手机约 3px）。
     * 如需固定方块大小，可设为具体正整数（如 4, 6, 8 等）。
     */
    cellSize: 0,

    // -------------------------------------------------------------------------
    // 3. 初始化逻辑选择（两种逻辑）
    // -------------------------------------------------------------------------
    /**
     * 页面初始化时的方块播撒逻辑：
     *   - 'preset': 【现有逻辑】预设图案模式。
     *               从滑翔机枪、多米诺、长寿种子库、滑翔机群等经典预设中加权随机选择并散落播撒。
     *   - 'random': 【全新逻辑】完全随机位置初始化模式。
     *               在整个网格中完全随机分布活细胞方块，位置彻底随机。
     */
    initMode: 'random', // 可选: 'preset' | 'random'

    /**
     * 完全随机模式下的活细胞方块初始密度（仅在 initMode 为 'random' 时生效）。
     * 取值范围 0.0 ~ 1.0。
     * 例如 0.15 表示大约 15% 的网格位置会被随机点亮为活细胞。
     * 推荐值：0.08（稀疏）~ 0.18（适中）。
     */
    randomDensity: 0.1,

    // -------------------------------------------------------------------------
    // 4. 运行中自动刷新/增添控制
    // -------------------------------------------------------------------------
    /**
     * 是否在生命游戏进行中自动刷新增添新方块。
     * - false : 【默认关闭】不在运行过程中自动增添新方块。
     *           每次只在浏览器刷新页面时初始化一次；
     *           页面未刷新情况下只持续进行现有的生命游戏演化。
     * - true  : 开启旧版逻辑（当活细胞过少或画面静止时，会自动补种随机方块）。
     */
    autoReplenish: false,

    /**
     * 防结壳 / 抖动老化清除机制（MAX_AGE）：
     * - 0  : 【推荐】纯正标准康威生命游戏规则（B3/S23）。
     *        静止方块永久存活，不会随着时间推移被强制消亡。
     * - >0 : 若某个位置静止连续超过该代数，该方块将强制消亡（旧版默认值为 14）。
     */
    maxAge: 0,

    /**
     * 是否在顶部吸顶导航栏区域避让方块（默认 true，避免遮挡顶栏文字）。
     */
    avoidHeader: true
  };
})(typeof window !== 'undefined' ? window : this);
